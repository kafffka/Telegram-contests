package org.telegram.messenger;

import static org.junit.Assert.fail;

import org.junit.Test;

import java.io.File;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;

/**
 * Keeps {@link VideoShapeOutlines} (the outlines shipped precomputed, so the app never traces them at runtime) in
 * sync with {@link VideoShapeBuilder#build}. When a shape changes, this test rewrites the table and fails once;
 * rerun it to confirm. Also runnable on its own: main() rewrites the table.
 */
public class VideoShapeOutlinesTest {

    static final File SOURCE = new File("src/main/java/org/telegram/messenger/VideoShapeOutlines.java");
    static final String[] NAMES = {"circle", "heart", "tree", "squircle", "star", "hexagon", "flower", "cloud", "blob", "cat", "ghost"};
    /** Two quantization steps of the 16-bit table. */
    static final float TOLERANCE = 2f / 65535f;
    static final int CHARS_PER_LINE = 128;

    @Test
    public void tableMatchesGeometry() throws IOException {
        for (int shape = 0; shape < VideoShape.COUNT; shape++) {
            float[] built = VideoShapeBuilder.build(shape, VideoShape.POINTS);
            float[] table = shape < VideoShapeOutlines.DATA.length ? VideoShape.decodeOutline(VideoShapeOutlines.DATA[shape]) : null;
            if (!matches(built, table)) {
                write();
                fail("VideoShapeOutlines was stale (" + NAMES[shape] + ") and has been regenerated, rerun the tests");
            }
        }
    }

    private static boolean matches(float[] built, float[] table) {
        if (table == null || table.length != built.length) {
            return false;
        }
        for (int i = 0; i < built.length; i++) {
            if (Math.abs(built[i] - table[i]) > TOLERANCE) {
                return false;
            }
        }
        return true;
    }

    static void write() throws IOException {
        Files.write(SOURCE.toPath(), generate().getBytes(StandardCharsets.UTF_8));
    }

    static String generate() {
        StringBuilder sb = new StringBuilder();
        sb.append("package org.telegram.messenger;\n\n");
        sb.append("/**\n");
        sb.append(" * Generated by VideoShapeOutlinesTest from VideoShapeBuilder (src/test), don't edit by hand: run the test\n");
        sb.append(" * after changing a shape. {@link VideoShape#POINTS} points per shape, indexed by shape id, each coordinate as\n");
        sb.append(" * 4 hex digits (0..ffff over the unit box), see {@link VideoShape#decodeOutline}.\n");
        sb.append(" */\n");
        sb.append("final class VideoShapeOutlines {\n\n");
        sb.append("    static final String[] DATA = {\n");
        for (int shape = 0; shape < VideoShape.COUNT; shape++) {
            float[] p = VideoShapeBuilder.build(shape, VideoShape.POINTS);
            StringBuilder hex = new StringBuilder();
            for (float v : p) {
                int q = Math.round(Math.max(0f, Math.min(1f, v)) * 65535f);
                hex.append(String.format("%04x", q));
            }
            sb.append("            // ").append(NAMES[shape]).append('\n');
            for (int i = 0; i < hex.length(); i += CHARS_PER_LINE) {
                sb.append(i == 0 ? "            \"" : "            + \"");
                sb.append(hex, i, Math.min(hex.length(), i + CHARS_PER_LINE)).append('"');
                sb.append(i + CHARS_PER_LINE >= hex.length() ? ",\n" : "\n");
            }
        }
        sb.append("    };\n\n");
        sb.append("    private VideoShapeOutlines() {\n");
        sb.append("    }\n");
        sb.append("}\n");
        return sb.toString();
    }

    public static void main(String[] args) throws IOException {
        write();
    }
}
